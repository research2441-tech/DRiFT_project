"""Transmon Hamiltonians (rotating frame), control operators, noise operators and targets."""
import numpy as np
import config as C


def ladder(d):
    return np.diag(np.sqrt(np.arange(1, d)), 1).astype(complex)


def kron(*ops):
    out = np.array([[1.0 + 0j]])
    for o in ops:
        out = np.kron(out, o)
    return out


class System:
    """Container for a controlled system: H(t) = H0 + sum_c u_c(t) Hc[c] + noise."""

    def __init__(self, name, H0, Hc, ctrl_bounds, P, target, sources, phase_ops, n_ops, a_ops):
        self.name = name
        self.H0 = H0
        self.Hc = np.array(Hc)
        self.ctrl_bounds = np.array(ctrl_bounds)
        self.P = P                      # projector onto the computational subspace (d_full x d_full)
        self.target = target            # target embedded in full space (acts on subspace)
        self.sources = sources          # list of dicts: name, kind ('add'|'mul'), op or ctrl idx
        self.phase_ops = phase_ops      # operators generating virtual-Z corrections (may be empty)
        self.n_ops = n_ops              # number operators (for Markovian dephasing)
        self.a_ops = a_ops              # lowering operators (for T1)
        self.dfull = H0.shape[0]
        self.dsub = int(round(np.real(np.trace(P))))
        self.comp_idx = np.where(np.abs(np.diag(P)) > 0.5)[0]


def _embed_1q(Gq, d=C.LEVELS):
    G = np.zeros((d, d), complex)
    G[:2, :2] = Gq
    return G


def single_transmon(gate="X"):
    d = C.LEVELS
    a = ladder(d)
    n = a.conj().T @ a
    H0 = 0.5 * C.ALPHA * (n @ n - n)
    Hx = 0.5 * (a + a.conj().T)
    Hy = 0.5j * (a.conj().T - a)
    P = np.diag([1, 1] + [0] * (d - 2)).astype(complex)
    X = np.array([[0, 1], [1, 0]], complex)
    if gate == "X":
        Gq = -1j * X                                   # exp(-i pi/2 X)
    elif gate == "SX":
        Gq = (np.eye(2) - 1j * X) / np.sqrt(2)         # exp(-i pi/4 X)
    elif gate == "H":
        Hd = np.array([[1, 1], [1, -1]], complex) / np.sqrt(2)
        Gq = -1j * Hd                                  # exp(-i pi/2 H)
    else:
        raise ValueError(gate)
    sources = [
        dict(name="freq", kind="add", op=n),
        dict(name="amp", kind="mul", ctrl=[0, 1]),
    ]
    return System(f"1Q-{gate}", H0, [Hx, Hy], [C.OMEGA_MAX, C.OMEGA_MAX], P,
                  _embed_1q(Gq), sources, phase_ops=[], n_ops=[n], a_ops=[a])


def two_transmons(gate="SQiSW"):
    """Two resonant transmons (qutrits) with a tunable exchange coupler.

    Controls: x1, y1, x2, y2 (local drives) and g (exchange coupling).
    Target: sqrt(iSWAP) on the computational subspace, with free virtual-Z phases.
    """
    d = C.LEVELS
    a = ladder(d)
    I = np.eye(d)
    n = a.conj().T @ a
    a1, a2 = kron(a, I), kron(I, a)
    n1, n2 = kron(n, I), kron(I, n)
    h0 = 0.5 * C.ALPHA * (n @ n - n)
    H0 = kron(h0, I) + kron(I, h0)
    Hx1 = 0.5 * (a1 + a1.conj().T)
    Hy1 = 0.5j * (a1.conj().T - a1)
    Hx2 = 0.5 * (a2 + a2.conj().T)
    Hy2 = 0.5j * (a2.conj().T - a2)
    Hg = a1.conj().T @ a2 + a1 @ a2.conj().T
    comp = [0, 1, d, d + 1]
    P = np.zeros((d * d, d * d), complex)
    for i in comp:
        P[i, i] = 1
    if gate != "SQiSW":
        raise ValueError(gate)
    # sqrt(iSWAP) in the convention exp(-i pi/8 (XX+YY)), generated by a positive exchange area
    s = 1 / np.sqrt(2)
    Gq = np.array([[1, 0, 0, 0], [0, s, -1j * s, 0], [0, -1j * s, s, 0], [0, 0, 0, 1]], complex)
    G = np.zeros((d * d, d * d), complex)
    for r, i in enumerate(comp):
        for c, j in enumerate(comp):
            G[i, j] = Gq[r, c]
    sources = [
        dict(name="freq1", kind="add", op=n1),
        dict(name="freq2", kind="add", op=n2),
        dict(name="amp", kind="mul", ctrl=[0, 1, 2, 3]),
        dict(name="coupler", kind="mul", ctrl=[4]),
    ]
    bounds = [C.OMEGA_MAX] * 4 + [C.G_MAX]
    return System("2Q-SQiSW", H0, [Hx1, Hy1, Hx2, Hy2, Hg], bounds, P, G, sources,
                  phase_ops=[n1, n2], n_ops=[n1, n2], a_ops=[a1, a2])


def get_system(gate):
    return two_transmons(gate) if gate == "SQiSW" else single_transmon(gate)
